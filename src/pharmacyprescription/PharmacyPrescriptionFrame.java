    private void attachEventHandlers() {
        btnAdd.addActionListener(evt -> addPrescription());
        btnProcess.addActionListener(evt -> processNextPrescription());
        btnSearch.addActionListener(evt -> searchPrescription());
    }

    private void addPrescription() {
        String id = txtPrescriptionId.getText().trim();
        String name = txtPatientName.getText().trim();
        String medication = txtMedication.getText().trim();

        if (id.isEmpty() || name.isEmpty() || medication.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please fill in Prescription ID, Patient Name, and Medication.",
                    "Missing Information",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        if (queue.searchById(id) != null) {
            JOptionPane.showMessageDialog(
                    this,
                    "A prescription with ID \"" + id + "\" already exists.",
                    "Duplicate Prescription ID",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Prescription prescription = new Prescription(id, name, medication, parseUrgency());
        if (!queue.enqueue(prescription)) {
            JOptionPane.showMessageDialog(
                    this,
                    "The queue is full. Process existing prescriptions before adding more.",
                    "Queue Full",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        refreshTable();
        clearInputFields();
    }

    private void processNextPrescription() {
        Prescription processed = queue.dequeue();
        if (processed == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "There are no prescriptions waiting to be processed.",
                    "Queue Empty",
                    JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                "Processed prescription:\n\n" + processed,
                "Prescription Processed",
                JOptionPane.INFORMATION_MESSAGE
        );
        refreshTable();
    }

    private void searchPrescription() {
        String searchId = txtSearchId.getText().trim();
        if (searchId.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please enter a Prescription ID to search.",
                    "Missing Search ID",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        Prescription found = queue.searchById(searchId);
        if (found == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "No prescription was found for ID \"" + searchId + "\".",
                    "Not Found",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        JOptionPane.showMessageDialog(
                this,
                found.toString(),
                "Prescription Found",
                JOptionPane.INFORMATION_MESSAGE
        );
    }
/**
 * Refreshes the JTable model to render all active queue elements.
 * Formats integer urgency levels into descriptive text strings for display.
 */
private void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) tblPrescriptions.getModel();
        model.setRowCount(0);

        Prescription[] records = queue.getAll();
        for (int i = 0; i < records.length; i++) {
            Prescription record = records[i];

            String urgencyLabel;
            switch (record.getUrgencyLevel()) {
                case 3:
                    urgencyLabel = "3 - High/Emergency";
                    break;
                case 2:
                    urgencyLabel = "2 - Medium";
                    break;
                default:
                    urgencyLabel = "1 - Low";
                    break;
            }

            model.addRow(new Object[] {
                record.getPrescriptionId(),
                record.getPatientName(),
                record.getMedication(),
                urgencyLabel
            });
        }
    }

    private void clearInputFields() {
        txtPrescriptionId.setText("");
        txtPatientName.setText("");
        txtMedication.setText("");
        cmbUrgency.setSelectedIndex(0);
        txtPrescriptionId.requestFocusInWindow();
    }

    private int parseUrgency() {
        Object selected = cmbUrgency.getSelectedItem();
        if (selected == null) {
            return 1;
        }
        String value = selected.toString();
        if (value.startsWith("3")) {
            return 3;
        }
        if (value.startsWith("2")) {
            return 2;
        }
        return 1;
    }

